ROWS = "ABCDEFGHIJK"
OFFSETS = {
    "B8L": ("B8", -0.28, 0.05),
    "B8R": ("B8", 0.28, 0.05),
    "C8U": ("C8", 0, -0.28),
}


def xy(code: str) -> tuple[float, float]:
    sq, dx, dy = OFFSETS.get(code, (code, 0.0, 0.0))
    col = int(sq[1:]) + dx
    row = ROWS.index(sq[0]) + dy
    return round((col - 0.5) / 10 * 100, 1), round((row + 0.5) / 11 * 100, 1)


def pt(pid: str, gid: str, resp: int, code: str, description: str) -> dict:
    x, y = xy(code)
    return {
        "id": pid,
        "groupId": gid,
        "resp": resp,
        "x": x,
        "y": y,
        "description": description,
    }


